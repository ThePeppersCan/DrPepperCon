import { Logger } from '../infrastructure/Logger.js';
import { EventDispatcher } from '../core/events/EventDispatcher.js';
import { RandomService } from '../core/random/RandomService.js';
import { EffectQueue } from '../core/effects/EffectQueue.js';
import { StateMachine, RUN_TRANSITIONS } from '../core/state/StateMachine.js';
import { CardEffectResolver } from '../core/effects/CardEffectResolver.js';
import { CardManager } from '../core/cards/CardManager.js';
import { ComboEngine } from '../core/combos/ComboEngine.js';
import { TacticalBoard } from '../core/tactics/TacticalBoard.js';
import { EventEffectResolver } from '../core/effects/EventEffectResolver.js';
import { RelicManager } from '../core/relics/RelicManager.js';
import { WeatherManager } from '../core/weather/WeatherManager.js';
import { AIManager } from '../core/ai/AIManager.js';
import { MatchManager } from '../core/match/MatchManager.js';
import { RunManager } from '../core/run/RunManager.js';
import { GameSimulation } from '../core/simulation/GameSimulation.js';
import { ReplayRecorder } from '../replay/ReplayRecorder.js';
import { StatisticsManager } from '../statistics/StatisticsManager.js';
import { AchievementManager } from '../achievements/AchievementManager.js';
import { UnlockManager } from '../progression/UnlockManager.js';
import { SettingsManager } from '../settings/SettingsManager.js';
import { ThemeManager } from '../themes/ThemeManager.js';
import { AnimationQueue } from '../animation/AnimationQueue.js';
import { AudioManager } from '../audio/AudioManager.js';
import { ParticleManager } from '../particles/ParticleManager.js';
import { InputManager } from '../input/InputManager.js';
import { SceneManager } from '../presentation/SceneManager.js';
import { CommandBus } from '../application/CommandBus.js';
import { SaveManager } from '../save/SaveManager.js';
import { DeveloperConsole } from '../debug/DeveloperConsole.js';
import { AssetManager } from '../assets/AssetManager.js';
import { LocalisationManager } from '../localisation/LocalisationManager.js';
import { MemoryManager } from '../memory/MemoryManager.js';
import { PerformanceMonitor } from '../debug/PerformanceMonitor.js';
import { DebugOverlay } from '../debug/DebugOverlay.js';

export function createServices(data) {
  const logger=new Logger({namespace:'QD'});
  const events=new EventDispatcher({logger});
  const random=new RandomService();
  const effectQueue=new EffectQueue({...data.config.effectSafety,logger});
  const stateMachine=new StateMachine(RUN_TRANSITIONS,logger);
  const settingsManager=new SettingsManager(events);
  const relics=new RelicManager(data,events);
  const weather=new WeatherManager(data,relics);
  const ai=new AIManager(data,random,events);
  const cardEffects=new CardEffectResolver({random,effectQueue,logger});
  const tacticalBoard=new TacticalBoard(data.config),cardManager=new CardManager(logger),comboEngine=new ComboEngine(tacticalBoard);
  const eventEffects=new EventEffectResolver({data,random,logger});
  const matchManager=new MatchManager({data,random,events,effectQueue,cardEffects,relics,weather,ai,stateMachine,cardManager,comboEngine,tacticalBoard,logger});
  const runManager=new RunManager({data,random,events,eventEffects,stateMachine,settingsManager,logger});
  const replay=new ReplayRecorder();
  const simulation=new GameSimulation({data,runManager,matchManager,replay,events,effectQueue});
  const statistics=new StatisticsManager(events);
  const achievements=new AchievementManager(events,data.achievements);
  const unlocks=new UnlockManager(data);
  const saveManager=new SaveManager({baseKey:'repo_quidditch_director_profile_v1',profileFactory:()=>simulation.newProfile(),profileSanitizer:x=>simulation.sanitizeProfile(x),logger});
  const animationQueue=new AnimationQueue(),inputManager=new InputManager(),audioManager=new AudioManager(settingsManager),particleManager=new ParticleManager(),themeManager=new ThemeManager(),sceneManager=new SceneManager(logger),commandBus=new CommandBus({events,logger});
  const assetManager=new AssetManager({logger}),localisationManager=new LocalisationManager(),memoryManager=new MemoryManager(),performanceMonitor=new PerformanceMonitor();
  const developerConsole=new DeveloperConsole({logger,events,statistics,effectQueue,data});
  const debugOverlay=new DebugOverlay({performanceMonitor,effectQueue,events});
  developerConsole.register('debug',()=>{debugOverlay.toggle();return 'debug overlay toggled';});
  return {logger,events,random,effectQueue,stateMachine,settingsManager,relics,weather,ai,cardEffects,cardManager,comboEngine,tacticalBoard,eventEffects,matchManager,runManager,replay,simulation,statistics,achievements,unlocks,saveManager,animationQueue,inputManager,audioManager,particleManager,themeManager,sceneManager,commandBus,assetManager,localisationManager,memoryManager,performanceMonitor,debugOverlay,developerConsole};
}
