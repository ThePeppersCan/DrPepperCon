-- REPO COMPANY — REPO ROOFTOPS
-- Repair/install for the Level Agility Repo Rooftops minigame.
-- Safe to run more than once. Does not replace or rename existing Harmony leaderboard functions.
-- Repo Rooftops GP is rebalanced to 20% of the original values (an 80% reduction).

create extension if not exists pgcrypto;

alter table public.characters add column if not exists gp integer not null default 0;
alter table public.characters add column if not exists agility_xp integer not null default 0;
alter table public.characters add column if not exists bank_items jsonb not null default '{}'::jsonb;

create table if not exists public.repo_rooftops_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  character_config jsonb not null default '{}'::jsonb,
  settings jsonb not null default '{}'::jsonb,
  best_height integer not null default 0 check (best_height >= 0),
  best_level integer not null default 0 check (best_level >= 0),
  mark_balance integer not null default 0 check (mark_balance >= 0),
  total_runs integer not null default 0 check (total_runs >= 0),
  total_gp_earned bigint not null default 0 check (total_gp_earned >= 0),
  total_metres bigint not null default 0 check (total_metres >= 0),
  total_playtime_ms bigint not null default 0 check (total_playtime_ms >= 0),
  stats jsonb not null default '{}'::jsonb,
  achievements jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.repo_rooftops_runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  mode text not null check (mode in ('endless','daily','hardcore','timetrial')),
  seed text not null,
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  claimed_at timestamptz,
  status text not null default 'active' check (status in ('active','claimed','abandoned','rejected')),
  highest_height integer not null default 0,
  completed_levels integer not null default 0,
  score bigint not null default 0,
  district text not null default 'Old Town Rooftops',
  max_momentum integer not null default 0,
  collectable_gp integer not null default 0,
  risk_gp integer not null default 0,
  marks_collected integer not null default 0,
  duration_ms bigint not null default 0,
  height_gp integer not null default 0,
  level_gp integer not null default 0,
  difficulty_gp integer not null default 0,
  momentum_gp integer not null default 0,
  personal_best_gp integer not null default 0,
  milestone_gp integer not null default 0,
  agility_xp_gained integer not null default 0,
  total_gp integer not null default 0,
  is_personal_best boolean not null default false,
  suspicious_reason text,
  created_at timestamptz not null default now()
);

create index if not exists repo_rooftops_runs_user_started_idx
  on public.repo_rooftops_runs(user_id, started_at desc);
create index if not exists repo_rooftops_runs_leaderboard_idx
  on public.repo_rooftops_runs(mode, status, highest_height desc, score desc);

