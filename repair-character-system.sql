-- CHARACTER SYSTEM REPAIR
-- Run this whole file once in Supabase -> SQL Editor.
-- It replaces only the broken character/minigame tables and functions.
-- It DOES NOT reset or modify the shared Dr Pepper counter.
-- Any old character rows are removed because the previous table schema was incomplete.

begin;

-- Remove old minigame functions first so a half-created table cannot keep stale definitions.
drop function if exists public.get_leaderboard();
drop function if exists public.collect_resource(uuid, text);
drop function if exists public.create_character(uuid, text);
drop function if exists public.get_character(uuid);
drop function if exists public.level_from_xp(integer);

-- Rebuild the character table with every column the website uses.
drop table if exists public.characters;

create table public.characters (
  id bigint generated by default as identity primary key,
  owner_token uuid not null unique,
  username text not null unique check (char_length(username) between 3 and 16),
  woodcutting_xp integer not null default 0 check (woodcutting_xp >= 0),
  mining_xp integer not null default 0 check (mining_xp >= 0),
  fishing_xp integer not null default 0 check (fishing_xp >= 0),
  collection text[] not null default '{}'::text[],
  created_at timestamptz not null default now()
);

alter table public.characters enable row level security;
revoke all on table public.characters from anon, authenticated;

create or replace function public.get_character(p_owner_token uuid)
returns table(
  username text,
  woodcutting_xp integer,
  mining_xp integer,
  fishing_xp integer,
  collection text[]
)
language sql
security definer
set search_path = public
as $$
  select c.username, c.woodcutting_xp, c.mining_xp, c.fishing_xp, c.collection
  from public.characters c
  where c.owner_token = p_owner_token
  limit 1;
$$;

create or replace function public.create_character(p_owner_token uuid, p_username text)
returns table(
  username text,
  woodcutting_xp integer,
  mining_xp integer,
  fishing_xp integer,
  collection text[]
)
language plpgsql
security definer
set search_path = public
as $$
declare
  clean_name text;
begin
  clean_name := btrim(p_username);

  if clean_name !~ '^[A-Za-z0-9 _-]{3,16}$' then
    raise exception 'Use 3-16 letters, numbers, spaces, - or _.';
  end if;

  if exists (select 1 from public.characters c where c.owner_token = p_owner_token) then
    raise exception 'This browser already has a character.';
  end if;

  insert into public.characters(owner_token, username)
  values (p_owner_token, clean_name);

  return query
  select c.username, c.woodcutting_xp, c.mining_xp, c.fishing_xp, c.collection
  from public.characters c
  where c.owner_token = p_owner_token;
end;
$$;

create or replace function public.collect_resource(p_owner_token uuid, p_skill text)
returns table(new_xp integer, xp_gained integer, drop_name text)
language plpgsql
security definer
set search_path = public
as $$
declare
  gain integer;
  updated_xp integer;
  drop_id text := null;
  drop_label text := null;
  roll double precision := random();
begin
  gain := case p_skill
    when 'woodcutting' then 25
    when 'mining' then 35
    when 'fishing' then 40
    else null
  end;

  if gain is null then
    raise exception 'Invalid skill';
  end if;

  if p_skill = 'woodcutting' then
    update public.characters
    set woodcutting_xp = woodcutting_xp + gain
    where owner_token = p_owner_token
    returning woodcutting_xp into updated_xp;
  elsif p_skill = 'mining' then
    update public.characters
    set mining_xp = mining_xp + gain
    where owner_token = p_owner_token
    returning mining_xp into updated_xp;
  else
    update public.characters
    set fishing_xp = fishing_xp + gain
    where owner_token = p_owner_token
    returning fishing_xp into updated_xp;
  end if;

  if updated_xp is null then
    raise exception 'Character not found';
  end if;

  if roll < 0.01 then
    if roll < 0.0005 then
      drop_id := 'golden_dr_pepper'; drop_label := 'Golden Dr Pepper';
    elsif roll < 0.002 then
      drop_id := 'reinforced_chair'; drop_label := 'Reinforced Chair';
    elsif roll < 0.0045 then
      drop_id := 'membership_card'; drop_label := 'Membership Card';
    elsif roll < 0.007 then
      drop_id := 'chair_fragment'; drop_label := 'Chair Fragment';
    else
      drop_id := 'mini_dr_pepper'; drop_label := 'Mini Dr Pepper';
    end if;

    update public.characters
    set collection = case
      when drop_id = any(collection) then collection
      else array_append(collection, drop_id)
    end
    where owner_token = p_owner_token;
  end if;

  return query select updated_xp, gain, drop_label;
end;
$$;

create or replace function public.level_from_xp(p_xp integer)
returns integer
language plpgsql
immutable
as $$
declare
  points integer := 0;
  lvl integer;
begin
  for lvl in 1..98 loop
    points := points + floor(lvl + 300 * power(2::numeric, lvl / 7.0))::integer;
    if p_xp < floor(points / 4.0) then
      return lvl;
    end if;
  end loop;
  return 99;
end;
$$;

create or replace function public.get_leaderboard()
returns table(username text, total_level integer)
language sql
security definer
set search_path = public
as $$
  select
    c.username,
    public.level_from_xp(c.woodcutting_xp)
      + public.level_from_xp(c.mining_xp)
      + public.level_from_xp(c.fishing_xp) as total_level
  from public.characters c
  order by total_level desc,
    (c.woodcutting_xp + c.mining_xp + c.fishing_xp) desc
  limit 10;
$$;

grant execute on function public.get_character(uuid) to anon, authenticated;
grant execute on function public.create_character(uuid, text) to anon, authenticated;
grant execute on function public.collect_resource(uuid, text) to anon, authenticated;
grant execute on function public.get_leaderboard() to anon, authenticated;

commit;
